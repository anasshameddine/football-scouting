-- Une ligne par joueur et saison : les transferts en cours de saison sont regroupés
-- (compteurs additionnés, club principal = celui où il a le plus joué).
select
    player_key,
    season,
    max(annee_debut)                                                as annee_debut,
    max(saison_label)                                               as saison_label,
    (array_agg(player order by minutes desc nulls last))[1]         as player,
    (array_agg(player_clean order by minutes desc nulls last))[1]   as player_clean,
    max(born)                                                       as born,
    max(age)                                                        as age,
    (array_agg(team order by minutes desc nulls last))[1]           as team,
    (array_agg(league order by minutes desc nulls last))[1]         as league,
    string_agg(team, ' / ' order by minutes desc nulls last)        as teams_all,
    count(distinct team)                                            as n_clubs,
    (array_agg(nation_code order by minutes desc nulls last))[1]    as nation_code,
    (array_agg(pos order by minutes desc nulls last))[1]            as pos,
    (array_agg(pos_main order by minutes desc nulls last))[1]       as pos_main,
    bool_or(nation_code = 'MAR')                                    as is_moroccan_fbref,
    max(tm_player_id)                                               as tm_player_id,
    max(tm_match)                                                   as tm_match,
    sum(minutes)                                                    as minutes,
    sum(performance_gls) as performance_gls,
    sum(performance_ast) as performance_ast,
    sum(performance_g_minus_pk) as performance_g_minus_pk,
    sum(performance_pk) as performance_pk,
    sum(performance_pkatt) as performance_pkatt,
    sum(performance_crdy) as performance_crdy,
    sum(performance_crdr) as performance_crdr,
    sum(performance_2crdy) as performance_2crdy,
    sum(performance_fls) as performance_fls,
    sum(performance_fld) as performance_fld,
    sum(performance_off) as performance_off,
    sum(performance_crs) as performance_crs,
    sum(performance_int) as performance_int,
    sum(performance_tklw) as performance_tklw,
    sum(performance_pkwon) as performance_pkwon,
    sum(performance_pkcon) as performance_pkcon,
    sum(performance_og) as performance_og,
    sum(standard_sh) as standard_sh,
    sum(standard_sot) as standard_sot,
    sum(us_xg) as us_xg,
    sum(us_np_xg) as us_np_xg,
    sum(us_xa) as us_xa,
    sum(us_shots) as us_shots,
    sum(us_key_passes) as us_key_passes,
    sum(us_xg_chain) as us_xg_chain,
    sum(us_xg_buildup) as us_xg_buildup,
    sum(us_minutes) as us_minutes,
    sum(matches) as matches,
    sum(starts) as starts,
    max(us_xg::text) is not null                                    as a_understat
from {{ ref('int_fbref_enrichi') }}
group by player_key, season
